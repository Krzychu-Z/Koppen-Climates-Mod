    // the four legs swing in diagonal pairs, like any four-legged walker
    private static void walk(ModelPart frontLeft, ModelPart frontRight, ModelPart backLeft, ModelPart backRight,
                             float limbSwing, float amount, float stride) {
        float a = Mth.cos(limbSwing * 0.6662F) * stride * amount;
        frontLeft.xRot += a;
        backRight.xRot += a;
        frontRight.xRot -= a;
        backLeft.xRot -= a;
    }

    @Override
    public void setupAnim(ElephantEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        walk(this.leg_fl, this.leg_fr, this.leg_bl, this.leg_br, limbSwing, limbSwingAmount, 0.7F);
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.4F;
        this.head.xRot = headPitch * Mth.DEG_TO_RAD * 0.3F;
        // the trunk curls and sways, the ears flap
        float sway = Mth.sin(ageInTicks * 0.06F);
        this.trunk.xRot += sway * 0.08F;
        this.trunk.zRot = Mth.sin(ageInTicks * 0.045F) * 0.12F + Mth.cos(limbSwing * 0.6662F) * 0.12F * limbSwingAmount;
        this.trunk2.xRot += sway * 0.12F;
        this.trunk3.xRot += Mth.sin(ageInTicks * 0.06F + 0.8F) * 0.18F;
        this.trunk_tip.xRot += Mth.sin(ageInTicks * 0.06F + 1.6F) * 0.25F;
        float flap = Mth.sin(ageInTicks * 0.1F) * 0.15F;
        this.ear_left.yRot += flap;
        this.ear_right.yRot -= flap;
        this.tail.zRot = Mth.sin(ageInTicks * 0.1F) * 0.2F;
    }
