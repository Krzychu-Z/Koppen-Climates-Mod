    // walking, the legs swing in diagonal pairs; flying (in harness before a boat, off the ground), they gallop
    // through the air, stretched out fore and aft
    @Override
    public void setupAnim(ReindeerEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        if (entity.isFlying()) {
            float g = Mth.sin(ageInTicks * 0.45F) * 0.35F;
            this.leg_fl.xRot = -1.1F + g;
            this.leg_fr.xRot = -1.0F + g;
            this.leg_bl.xRot = 1.1F - g;
            this.leg_br.xRot = 1.0F - g;
            this.head.xRot -= 0.25F;
        } else {
            float a = Mth.cos(limbSwing * 0.6662F) * 1.1F * limbSwingAmount;
            this.leg_fl.xRot += a;
            this.leg_br.xRot += a;
            this.leg_fr.xRot -= a;
            this.leg_bl.xRot -= a;
            this.head.xRot += headPitch * Mth.DEG_TO_RAD * 0.4F;
        }
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.5F;
        this.tail.xRot += Mth.sin(ageInTicks * 0.25F) * 0.2F;
    }

