package net.krisplis.koppenclimate.client;

import net.krisplis.koppenclimate.KoppenClimateMod;
import net.krisplis.koppenclimate.entity.custom.GiraffeEntity;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

// Generated by the mod's savanna-animal model script (the boxes match textures/entity/giraffe.png).
public class GiraffeModel extends HierarchicalModel<GiraffeEntity> {
    public static final ModelLayerLocation LAYER =
            new ModelLayerLocation(ResourceLocation.fromNamespaceAndPath(KoppenClimateMod.MOD_ID, "giraffe"), "main");

    private final ModelPart root;
    private final ModelPart body;
    private final ModelPart leg_fl;
    private final ModelPart leg_fr;
    private final ModelPart leg_bl;
    private final ModelPart leg_br;
    private final ModelPart neck;
    private final ModelPart head;
    private final ModelPart tail;

    public GiraffeModel(ModelPart root) {
        this.root = root;
        this.body = root.getChild("body");
        this.leg_fl = root.getChild("leg_fl");
        this.leg_fr = root.getChild("leg_fr");
        this.leg_bl = root.getChild("leg_bl");
        this.leg_br = root.getChild("leg_br");
        this.neck = root.getChild("neck");
        this.head = this.neck.getChild("head");
        this.tail = root.getChild("tail");
    }

    @SuppressWarnings("unused")
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p_body = root.addOrReplaceChild("body", CubeListBuilder.create().texOffs(0, 0).addBox(-7.0F, -27.0F, -12.0F, 14, 16, 24),
                PartPose.offsetAndRotation(0.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_fl = root.addOrReplaceChild("leg_fl", CubeListBuilder.create().texOffs(76, 0).addBox(-2.0F, 0.0F, -2.0F, 4, 36, 4),
                PartPose.offsetAndRotation(4.0F, -12.0F, -8.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_fr = root.addOrReplaceChild("leg_fr", CubeListBuilder.create().texOffs(92, 0).addBox(-2.0F, 0.0F, -2.0F, 4, 36, 4),
                PartPose.offsetAndRotation(-4.0F, -12.0F, -8.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_bl = root.addOrReplaceChild("leg_bl", CubeListBuilder.create().texOffs(108, 0).addBox(-2.0F, 0.0F, -2.0F, 4, 36, 4),
                PartPose.offsetAndRotation(4.0F, -12.0F, 8.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_br = root.addOrReplaceChild("leg_br", CubeListBuilder.create().texOffs(0, 40).addBox(-2.0F, 0.0F, -2.0F, 4, 36, 4),
                PartPose.offsetAndRotation(-4.0F, -12.0F, 8.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_neck = root.addOrReplaceChild("neck", CubeListBuilder.create().texOffs(16, 40).addBox(-3.0F, -40.0F, -3.0F, 6, 40, 6).texOffs(40, 40).addBox(-1.0F, -38.0F, 3.0F, 2, 36, 1),
                PartPose.offsetAndRotation(0.0F, -23.0F, -10.0F, 0.3F, 0.0F, 0.0F));
        PartDefinition p_head = p_neck.addOrReplaceChild("head", CubeListBuilder.create().texOffs(46, 40).addBox(-3.0F, -4.0F, -10.0F, 6, 6, 11).texOffs(80, 40).addBox(-3.0F, -7.0F, -1.0F, 2, 3, 2).texOffs(88, 40).addBox(1.0F, -7.0F, -1.0F, 2, 3, 2).texOffs(96, 40).addBox(-5.0F, -4.0F, -1.0F, 2, 1, 3).texOffs(106, 40).addBox(3.0F, -4.0F, -1.0F, 2, 1, 3),
                PartPose.offsetAndRotation(0.0F, -40.0F, 0.0F, -0.3F, 0.0F, 0.0F));
        PartDefinition p_tail = root.addOrReplaceChild("tail", CubeListBuilder.create().texOffs(116, 40).addBox(-1.0F, 0.0F, 0.0F, 2, 16, 1).texOffs(0, 86).addBox(-1.5F, 16.0F, -0.5F, 3, 4, 2),
                PartPose.offsetAndRotation(0.0F, -25.0F, 12.0F, 0.15F, 0.0F, 0.0F));
        return LayerDefinition.create(mesh, 128, 128);
    }

    @Override
    public ModelPart root() {
        return this.root;
    }

    // the four legs swing in diagonal pairs, like any four-legged walker
    private static void walk(ModelPart frontLeft, ModelPart frontRight, ModelPart backLeft, ModelPart backRight,
                             float limbSwing, float amount, float stride) {
        float a = Mth.cos(limbSwing * 0.6662F) * stride * amount;
        frontLeft.xRot += a;
        backRight.xRot += a;
        frontRight.xRot -= a;
        backLeft.xRot -= a;
    }

    @Override
    public void setupAnim(GiraffeEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        walk(this.leg_fl, this.leg_fr, this.leg_bl, this.leg_br, limbSwing, limbSwingAmount, 0.6F);
        // the neck stoops right down to let a rider climb on, then lifts them back up
        float down = 1.0F - entity.getLiftProgress(ageInTicks - (float) entity.tickCount);
        this.neck.xRot += down * 2.0F;
        this.head.xRot -= down * 2.0F;
        this.neck.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.3F;
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.3F;
        this.head.xRot += headPitch * Mth.DEG_TO_RAD * 0.4F;
        this.neck.xRot += Mth.sin(ageInTicks * 0.05F) * 0.03F;
        this.tail.zRot = Mth.sin(ageInTicks * 0.1F) * 0.25F;
    }
}
