import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

// Generated by the mod's savanna-animal model script (the boxes match textures/entity/lion.png).
public class LionModel extends HierarchicalModel<LionEntity> {
    public static final ModelLayerLocation LAYER =
            new ModelLayerLocation(ResourceLocation.fromNamespaceAndPath(KoppenClimateMod.MOD_ID, "lion"), "main");

    private final ModelPart root;
    private final ModelPart body;
    private final ModelPart leg_fl;
    private final ModelPart leg_fr;
    private final ModelPart leg_bl;
    private final ModelPart leg_br;
    private final ModelPart head;
    private final ModelPart tail;

    public LionModel(ModelPart root) {
        this.root = root;
        this.body = root.getChild("body");
        this.leg_fl = root.getChild("leg_fl");
        this.leg_fr = root.getChild("leg_fr");
        this.leg_bl = root.getChild("leg_bl");
        this.leg_br = root.getChild("leg_br");
        this.head = root.getChild("head");
        this.tail = root.getChild("tail");
    }

    @SuppressWarnings("unused")
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p_body = root.addOrReplaceChild("body", CubeListBuilder.create().texOffs(0, 0).addBox(-6.0F, 6.0F, -13.0F, 12, 11, 26),
                PartPose.offsetAndRotation(0.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_fl = root.addOrReplaceChild("leg_fl", CubeListBuilder.create().texOffs(76, 0).addBox(-2.0F, 0.0F, -2.0F, 4, 9, 4),
                PartPose.offsetAndRotation(4.0F, 15.0F, -9.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_fr = root.addOrReplaceChild("leg_fr", CubeListBuilder.create().texOffs(92, 0).addBox(-2.0F, 0.0F, -2.0F, 4, 9, 4),
                PartPose.offsetAndRotation(-4.0F, 15.0F, -9.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_bl = root.addOrReplaceChild("leg_bl", CubeListBuilder.create().texOffs(108, 0).addBox(-2.0F, 0.0F, -2.0F, 4, 9, 4),
                PartPose.offsetAndRotation(4.0F, 15.0F, 9.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_br = root.addOrReplaceChild("leg_br", CubeListBuilder.create().texOffs(0, 37).addBox(-2.0F, 0.0F, -2.0F, 4, 9, 4),
                PartPose.offsetAndRotation(-4.0F, 15.0F, 9.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_head = root.addOrReplaceChild("head", CubeListBuilder.create().texOffs(16, 37).addBox(-5.0F, -5.0F, -8.0F, 10, 10, 8).texOffs(52, 37).addBox(-7.0F, -7.0F, -3.0F, 14, 15, 6).texOffs(92, 37).addBox(-3.0F, 0.0F, -11.0F, 6, 4, 3).texOffs(110, 37).addBox(-5.0F, -7.0F, -5.0F, 2, 2, 1).texOffs(116, 37).addBox(3.0F, -7.0F, -5.0F, 2, 2, 1),
                PartPose.offsetAndRotation(0.0F, 9.0F, -13.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_tail = root.addOrReplaceChild("tail", CubeListBuilder.create().texOffs(0, 58).addBox(-1.0F, 0.0F, 0.0F, 2, 2, 13).texOffs(30, 58).addBox(-1.5F, -0.5F, 13.0F, 3, 3, 3),
                PartPose.offsetAndRotation(0.0F, 8.0F, 13.0F, -1.0F, 0.0F, 0.0F));
        return LayerDefinition.create(mesh, 128, 128);
    }

    @Override
    public ModelPart root() {
        return this.root;
    }

    // the four legs swing in diagonal pairs, like any four-legged walker
    private static void walk(ModelPart frontLeft, ModelPart frontRight, ModelPart backLeft, ModelPart backRight,
                             float limbSwing, float amount, float stride) {
        float a = Mth.cos(limbSwing * 0.6662F) * stride * amount;
        frontLeft.xRot += a;
        backRight.xRot += a;
        frontRight.xRot -= a;
        backLeft.xRot -= a;
    }

    @Override
    public void setupAnim(LionEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        walk(this.leg_fl, this.leg_fr, this.leg_bl, this.leg_br, limbSwing, limbSwingAmount, 1.2F);
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.6F;
        this.head.xRot = headPitch * Mth.DEG_TO_RAD * 0.6F;
        this.tail.yRot = Mth.sin(ageInTicks * 0.08F) * 0.3F;
        this.tail.xRot += Mth.cos(limbSwing * 0.6662F) * 0.2F * limbSwingAmount;
    }
}
