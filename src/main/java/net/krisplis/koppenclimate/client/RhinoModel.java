    // the four legs swing in diagonal pairs, like any four-legged walker
    private static void walk(ModelPart frontLeft, ModelPart frontRight, ModelPart backLeft, ModelPart backRight,
                             float limbSwing, float amount, float stride) {
        float a = Mth.cos(limbSwing * 0.6662F) * stride * amount;
        frontLeft.xRot += a;
        backRight.xRot += a;
        frontRight.xRot -= a;
        backLeft.xRot -= a;
    }

    @Override
    public void setupAnim(RhinoEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        walk(this.leg_fl, this.leg_fr, this.leg_bl, this.leg_br, limbSwing, limbSwingAmount, 1.0F);
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.4F;
        this.head.xRot += headPitch * Mth.DEG_TO_RAD * 0.3F + Mth.cos(limbSwing * 0.6662F * 2.0F) * 0.05F * limbSwingAmount;
        this.tail.zRot = Mth.sin(ageInTicks * 0.12F) * 0.3F;
    }
