    // the four legs swing in diagonal pairs; the head looks about, a little; the short tail flicks
    @Override
    public void setupAnim(MooseEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        float a = Mth.cos(limbSwing * 0.6662F) * 0.9F * limbSwingAmount;
        this.leg_fl.xRot += a;
        this.leg_br.xRot += a;
        this.leg_fr.xRot -= a;
        this.leg_bl.xRot -= a;
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.5F;
        this.head.xRot += headPitch * Mth.DEG_TO_RAD * 0.3F;
        // lowered for the charge
        if (entity.isAggressive()) this.head.xRot += 0.45F;
        this.tail.xRot += Mth.sin(ageInTicks * 0.2F) * 0.15F;
    }

