package net.krisplis.koppenclimate.client;

import net.krisplis.koppenclimate.KoppenClimateMod;
import net.krisplis.koppenclimate.entity.custom.DustDevilEntity;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;


// Generated by the mod's quadruped model script (the boxes match textures/entity/dust_devil.png).
public class DustDevilModel extends HierarchicalModel<DustDevilEntity> {
    public static final ModelLayerLocation LAYER =
            new ModelLayerLocation(ResourceLocation.fromNamespaceAndPath(KoppenClimateMod.MOD_ID, "dust_devil"), "main");

    private final ModelPart root;
    private final ModelPart seg0;
    private final ModelPart seg1;
    private final ModelPart seg2;
    private final ModelPart seg3;
    private final ModelPart seg4;
    private final ModelPart seg5;
    private final ModelPart seg6;

    public DustDevilModel(ModelPart root) {
        this.root = root;
        this.seg0 = root.getChild("seg0");
        this.seg1 = root.getChild("seg1");
        this.seg2 = root.getChild("seg2");
        this.seg3 = root.getChild("seg3");
        this.seg4 = root.getChild("seg4");
        this.seg5 = root.getChild("seg5");
        this.seg6 = root.getChild("seg6");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p_seg0 = root.addOrReplaceChild("seg0", CubeListBuilder.create().texOffs(16, 64).addBox(-1.0F, -2.5F, -1.0F, 2, 5, 2),
                PartPose.offsetAndRotation(0.0F, 21.5F, 0.0F, 0F, 0F, 0F));
        PartDefinition p_seg1 = root.addOrReplaceChild("seg1", CubeListBuilder.create().texOffs(0, 64).addBox(-2.0F, -2.5F, -2.0F, 4, 5, 4),
                PartPose.offsetAndRotation(0.0F, 16.5F, 0.0F, 0F, 0F, 0F));
        PartDefinition p_seg2 = root.addOrReplaceChild("seg2", CubeListBuilder.create().texOffs(32, 51).addBox(-3.0F, -2.5F, -3.0F, 6, 5, 6),
                PartPose.offsetAndRotation(0.0F, 11.5F, 0.0F, 0F, 0F, 0F));
        PartDefinition p_seg3 = root.addOrReplaceChild("seg3", CubeListBuilder.create().texOffs(0, 51).addBox(-4.0F, -2.5F, -4.0F, 8, 5, 8),
                PartPose.offsetAndRotation(0.0F, 6.5F, 0.0F, 0F, 0F, 0F));
        PartDefinition p_seg4 = root.addOrReplaceChild("seg4", CubeListBuilder.create().texOffs(0, 36).addBox(-5.0F, -2.5F, -5.0F, 10, 5, 10),
                PartPose.offsetAndRotation(0.0F, 1.5F, 0.0F, 0F, 0F, 0F));
        PartDefinition p_seg5 = root.addOrReplaceChild("seg5", CubeListBuilder.create().texOffs(0, 19).addBox(-6.0F, -2.5F, -6.0F, 12, 5, 12),
                PartPose.offsetAndRotation(0.0F, -3.5F, 0.0F, 0F, 0F, 0F));
        PartDefinition p_seg6 = root.addOrReplaceChild("seg6", CubeListBuilder.create().texOffs(0, 0).addBox(-7.0F, -2.5F, -7.0F, 14, 5, 14),
                PartPose.offsetAndRotation(0.0F, -8.5F, 0.0F, 0F, 0F, 0F));
        return LayerDefinition.create(mesh, 64, 128);
    }

    @Override
    public ModelPart root() {
        return this.root;
    }

    // each ring of the funnel spins on its own, the lower ones faster, and the whole column sways and wanders
    // about its foot
    @Override
    public void setupAnim(DustDevilEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        ModelPart[] rings = {this.seg0, this.seg1, this.seg2, this.seg3, this.seg4, this.seg5, this.seg6};
        for (int i = 0; i < rings.length; i++) {
            ModelPart ring = rings[i];
            ring.yRot = ageInTicks * (0.9F - i * 0.08F) + i * 0.7F;
            float sway = i * 0.35F;
            ring.x += Mth.sin(ageInTicks * 0.13F + i * 0.5F) * sway;
            ring.z += Mth.cos(ageInTicks * 0.11F + i * 0.4F) * sway;
        }
    }

}
